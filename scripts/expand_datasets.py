    existing = {e["topic"] for e in data["entries"]}
    new_entries = []
    next_id = len(data["entries"]) + 1

    for prefix, stmts in MORE_DRIFT:
        if prefix not in existing:
            parts = prefix.split("→")
            new_entries.append({
                "id": f"SCS-DRF-{next_id:04d}",
                "topic": prefix, "statements": stmts,
                "label": "drift", "expected_cv": "> 0.3",
                "drift_type": "topic_transition",
                "description": f"从{parts[0]}话题逐步漂移到{parts[1]}话题",
            })
            next_id += 1

    for prefix, stmts in MORE_INCR_DRIFT:
        if prefix not in existing:
            base = stmts[0].split("（")[0].split("(")[0].strip()
            new_entries.append({
                "id": f"SCS-DRF-{next_id:04d}",
                "topic": f"增量漂移-{prefix}",
                "statements": stmts, "label": "drift",
                "expected_cv": "> 0.4",
                "drift_type": "incremental_contradiction",
                "description": f"围绕'{base}'的渐进取反序列,从完全一致到完全矛盾",
            })
            next_id += 1

    data["entries"].extend(new_entries)
    data["metadata"]["total"] = len(data["entries"])
    save_json("scs_drift.json", data)
    print(f"SCS Drift: {len(data['entries'])} (+{len(new_entries)})")
    return data

