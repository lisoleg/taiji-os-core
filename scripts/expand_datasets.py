def expand_consistent():
    data = load_json("hdr_consistent.json")
    existing = {(e["statement_a"], e["statement_b"]) for e in data["entries"]}
    new_entries = []
    next_id = len(data["entries"]) + 1
    for a, b in MORE_CONSISTENT:
        if (a, b) not in existing:
            new_entries.append({
                "id": f"HDR-CON-{next_id:04d}",
                "category": "consistent",
                "subtype": "real_world_knowledge",
                "statement_a": a, "statement_b": b,
                "label": "consistent",
            })
            next_id += 1
    data["entries"].extend(new_entries)
    data["metadata"]["total"] = len(data["entries"])
    save_json("hdr_consistent.json", data)
    print(f"HDR Consistent: {len(data['entries'])} (+{len(new_entries)})")
    return data

