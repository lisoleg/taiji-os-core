def load_json(name):
    with open(os.path.join(OUTPUT_DIR, name), "r", encoding="utf-8") as f:
        return json.load(f)

def save_json(name, data):
    with open(os.path.join(OUTPUT_DIR, name), "w", encoding="utf-8") as f:
        json.dump(data, f, ensure_ascii=False, indent=2)

def expand_stable():
    data = load_json("scs_stable.json")
    existing = {e["topic"] for e in data["entries"]}
    next_id = len(data["entries"]) + 1
    added = 0
    for name, stmts in STABLE_TOPICS:
        if name not in existing:
            data["entries"].append({
                "id": f"SCS-STB-{next_id:04d}",
                "topic": name, "statements": stmts,
                "label": "stable", "expected_cv": "< 0.1",
                "description": f"{name}相关的一致陈述序列,预期ψ高度稳定",
            })
            next_id += 1; added += 1
    data["metadata"]["total"] = len(data["entries"])
    save_json("scs_stable.json", data)
    return len(data["entries"]), added

def expand_drift():
    data = load_json("scs_drift.json")
    existing = {e["topic"] for e in data["entries"]}
    next_id = len(data["entries"]) + 1
    added = 0

    for prefix, stmts in DRIFT_SEQUENCES:
        if prefix not in existing:
            parts = prefix.split("→")
            data["entries"].append({
                "id": f"SCS-DRF-{next_id:04d}",
                "topic": prefix, "statements": stmts,
                "label": "drift", "expected_cv": "> 0.3",
                "drift_type": "topic_transition",
                "description": f"从{parts[0]}话题逐步漂移到{parts[1]}话题",
            })
            next_id += 1; added += 1

    for prefix, stmts in INCR_DRIFT:
        if prefix not in existing:
            base = stmts[0].split("（")[0].split("(")[0].strip()
            data["entries"].append({
                "id": f"SCS-DRF-{next_id:04d}",
                "topic": f"增量漂移-{prefix}",
                "statements": stmts, "label": "drift",
                "expected_cv": "> 0.4",
                "drift_type": "incremental_contradiction",
                "description": f"围绕'{base}'的渐进取反序列,从完全一致到完全矛盾",
            })
            next_id += 1; added += 1

    data["metadata"]["total"] = len(data["entries"])
    save_json("scs_drift.json", data)
    return len(data["entries"]), added

