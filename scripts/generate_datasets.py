def generate_scs_stable() -> list[dict]:
    return [{
        "id":f"SCS-STB-{i+1:04d}","topic":name,"statements":stmts,
        "label":"stable","expected_cv":"< 0.1",
        "description":f"{name}相关的一致陈述序列,预期ψ高度稳定",
    } for i,(name,stmts) in enumerate(SCS_TOPICS)]

def generate_scs_drift() -> list[dict]:
    entries = []
    tid = 0
    for prefix, stmts in DRIFT_SEQUENCES:
        tid += 1
        parts = prefix.split("→")
        entries.append({
            "id":f"SCS-DRF-{tid:04d}","topic":prefix,"statements":stmts,
            "label":"drift","expected_cv":"> 0.3","drift_type":"topic_transition",
            "description":f"从{parts[0]}话题逐步漂移到{parts[1]}话题",
        })
    for prefix, stmts in INCR_DRIFT:
        tid += 1
        base = stmts[0].split("（")[0].split("(")[0].strip()
        entries.append({
            "id":f"SCS-DRF-{tid:04d}","topic":f"增量漂移-{prefix}",
            "statements":stmts,"label":"drift","expected_cv":"> 0.4",
            "drift_type":"incremental_contradiction",
            "description":f"围绕'{base}'的渐进取反序列,从完全一致到完全矛盾",
        })
    return entries

