# ============ 生成函数 ============

def generate_contradictions() -> list[dict]:
    entries = []
    tid = 0

    def add(cat, a, b, subtype=""):
        nonlocal tid; tid += 1
        entries.append({
            "id": f"HDR-CON-{tid:04d}","category": cat,"subtype": subtype,
            "statement_a": a,"statement_b": b,"label": "contradiction",
            "contradiction_type": "explicit" if any(
                kw in a+b for kw in ["矛盾","冲突","不一致","相反"]
            ) else "implicit",
        })

    for tmpl in SPATIAL_TEMPLATES:
        for (s1,s2) in SPATIAL_LOCS:
            s3,s4 = random.choice(SPATIAL_LOCS)
            add("spatial", tmpl[0].format(s1=s1,s2=s2,s3=s3,s4=s4),
                tmpl[1].format(s1=s1,s2=s2,s3=s3,s4=s4), f"{s1}-vs-{s2}")

    for tmpl in TEMPORAL_TEMPLATES:
        for (t1,t2) in TEMPORAL_DATES:
            t3,t4 = random.choice(TEMPORAL_DATES)
            add("temporal", tmpl[0].format(t1=t1,t2=t2,t3=t3,t4=t4),
                tmpl[1].format(t1=t1,t2=t2,t3=t3,t4=t4), f"{t1}-vs-{t2}")

    for tmpl in LOGICAL_TEMPLATES:
        add("logical", tmpl[0], tmpl[1], "A-and-not-A")

    for tmpl in NUMERICAL_TEMPLATES:
        for (n1,n2) in NUMERICAL_PAIRS:
            add("numerical", tmpl[0].format(n1=n1,n2=n2),
                tmpl[1].format(n1=n1,n2=n2), f"{n1}-vs-{n2}")

    for tmpl in CAUSAL_TEMPLATES:
        for (c1,c2) in CAUSAL_PAIRS:
            add("causal", tmpl[0].format(c1=c1,c2=c2),
                tmpl[1].format(c1=c1,c2=c2), f"{c1}->{c2}")

    for tmpl in ATTRIBUTE_TEMPLATES:
        for (a1,a2) in ATTRIBUTE_PAIRS:
            add("attribute", tmpl[0].format(a1=a1,a2=a2),
                tmpl[1].format(a1=a1,a2=a2), f"{a1}-vs-{a2}")

    for tmpl in REFERENTIAL_TEMPLATES:
        for r1 in REFERENTIAL_ENTITIES:
            r2 = random.choice(REFERENTIAL_ENTITIES)
            r3 = f"第{random.randint(1,50)}条"
            c1,c2 = random.choice(REFERENTIAL_CLAIMS)
            n1,n2 = random.randint(60,95), random.randint(20, n1-10)
            add("referential", tmpl[0].format(r1=r1,r2=r2,r3=r3,c1=c1,n1=n1,n2=n2),
                tmpl[1].format(r1=r1,r2=r2,r3=r3,c1=c1,c2=c2,n1=n1,n2=n2), r1)

    for tmpl in DRIFT_TEMPLATES:
        for (a1,a2) in DRIFT_PAIRS:
            add("semantic_drift", tmpl[0].format(a1=a1,a2=a2),
                tmpl[1].format(a1=a1,a2=a2), f"{a1}%-vs-{a2}%")

    return entries


