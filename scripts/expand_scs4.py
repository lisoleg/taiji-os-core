def main():
    # 稳定
    data = load_json("scs_stable.json")
    existing = {e["topic"] for e in data["entries"]}
    nid = len(data["entries"]) + 1; added = 0
    for name, stmts in STABLE_EXTRA:
        if name not in existing:
            data["entries"].append({
                "id": f"SCS-STB-{nid:04d}","topic": name,"statements": stmts,
                "label":"stable","expected_cv":"< 0.1",
                "description": f"{name}相关的一致陈述序列",
            })
            nid += 1; added += 1
    data["metadata"]["total"] = len(data["entries"])
    save_json("scs_stable.json", data)
    print(f"SCS Stable: {len(data['entries'])} (+{added})")

    # 漂移
    data = load_json("scs_drift.json")
    existing = {e["topic"] for e in data["entries"]}
    nid = len(data["entries"]) + 1; added = 0

    for prefix, stmts in DRIFT_EXTRA:
        if prefix not in existing:
            parts = prefix.split("→")
            data["entries"].append({
                "id": f"SCS-DRF-{nid:04d}","topic": prefix,"statements": stmts,
                "label":"drift","expected_cv":"> 0.3","drift_type":"topic_transition",
                "description": f"从{parts[0]}话题逐步漂移到{parts[1]}话题",
            })
            nid += 1; added += 1

    for prefix, stmts in INCR_EXTRA:
        tp = f"增量漂移-{prefix}"
        if tp not in existing:
            base = stmts[0].split("（")[0].split("(")[0].strip()
            data["entries"].append({
                "id": f"SCS-DRF-{nid:04d}","topic": tp,
                "statements": stmts,"label":"drift","expected_cv":"> 0.4",
                "drift_type":"incremental_contradiction",
                "description": f"围绕'{base}'的渐进取反序列",
            })
            nid += 1; added += 1

    data["metadata"]["total"] = len(data["entries"])
    save_json("scs_drift.json", data)
    print(f"SCS Drift:  {len(data['entries'])} (+{added})")

    print("\n✅ Final expansion done!")

if __name__ == "__main__":
    main()
